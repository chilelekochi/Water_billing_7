CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
BEGIN
 IF p_units IS NULL OR p_units<0 THEN RAISE EXCEPTION 'Consumption must be non-negative and not NULL'; END IF;
 RETURN (LEAST(p_units,10)*5 + GREATEST(p_units-10,0)*8)::NUMERIC(12,2);
END $$;

CREATE OR REPLACE FUNCTION trg_validate_reading()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.current_reading<NEW.previous_reading THEN
   RAISE EXCEPTION 'Current meter reading cannot be below previous reading';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER tr_reading_check
BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW EXECUTE FUNCTION trg_validate_reading();

CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id INT,p_due_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_previous NUMERIC(12,2); v_current NUMERIC(12,2);
BEGIN
 SELECT previous_reading,current_reading INTO v_previous,v_current
 FROM readings WHERE reading_id=p_reading_id;
 IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading ID: %',p_reading_id; END IF;
 IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date cannot be NULL'; END IF;
 IF EXISTS(SELECT 1 FROM bills WHERE reading_id=p_reading_id) THEN
   RAISE EXCEPTION 'A bill already exists for reading %',p_reading_id;
 END IF;
 INSERT INTO bills(reading_id,charge,amount_paid,due_on)
 VALUES(p_reading_id,fn_water_charge(v_current-v_previous),0,p_due_on);
END $$;

CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT c.full_name,b.due_on,(b.charge-b.amount_paid) AS outstanding_amount
FROM bills b JOIN readings r ON r.reading_id=b.reading_id
JOIN customers c ON c.customer_id=r.customer_id
WHERE b.due_on<CURRENT_DATE AND b.amount_paid<b.charge;

CREATE INDEX idx_bills_due_unpaid ON bills(due_on) WHERE amount_paid<charge;
EXPLAIN SELECT bill_id,due_on,charge-amount_paid AS outstanding
FROM bills WHERE due_on<CURRENT_DATE AND amount_paid<charge;

CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql AS $$
BEGIN
 INSERT INTO receivable_snapshot(snapshot_date,total_due)
 SELECT CURRENT_DATE,COALESCE(SUM(charge-amount_paid),0)
 FROM bills WHERE amount_paid<charge
 ON CONFLICT(snapshot_date) DO UPDATE SET total_due=EXCLUDED.total_due;
END $$;

CALL pr_generate_bill(1,CURRENT_DATE+14);
CALL pr_generate_bill(2,CURRENT_DATE-2);
CALL pr_refresh_receivables();
