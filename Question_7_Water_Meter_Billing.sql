SET search_path TO q7_water, public;

DROP VIEW IF EXISTS v_overdue_bills;
DROP TABLE IF EXISTS receivable_snapshot,bills,readings,customers CASCADE;
DROP FUNCTION IF EXISTS fn_water_charge(NUMERIC);
DROP PROCEDURE IF EXISTS pr_generate_bill(INT,DATE);
DROP PROCEDURE IF EXISTS pr_refresh_receivables();

CREATE TABLE customers (
 customer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL
);
CREATE TABLE readings (
 reading_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id INT NOT NULL REFERENCES customers(customer_id),
 reading_month DATE NOT NULL CHECK(EXTRACT(DAY FROM reading_month)=1),
 previous_reading NUMERIC(12,2) NOT NULL CHECK(previous_reading>=0),
 current_reading NUMERIC(12,2) NOT NULL CHECK(current_reading>=0),
 UNIQUE(customer_id,reading_month)
);
CREATE TABLE bills (
 bill_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reading_id INT NOT NULL UNIQUE REFERENCES readings(reading_id),
 charge NUMERIC(12,2) NOT NULL CHECK(charge>=0),
 amount_paid NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(amount_paid>=0 AND amount_paid<=charge),
 due_on DATE NOT NULL
);
CREATE TABLE receivable_snapshot (
 snapshot_date DATE PRIMARY KEY,
 total_due NUMERIC(14,2) NOT NULL
);
